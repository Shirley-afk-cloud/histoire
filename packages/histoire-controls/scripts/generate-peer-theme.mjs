import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
// Resolve through root: docs/examples intentionally retain the exact v3 palette.
const rootRequire = createRequire(new URL('../../../package.json', import.meta.url))
const colors = rootRequire('tailwindcss/colors')
const { getHistoireColorChannels, parseColor } = require('@histoire/protocol')

const inherited = rootRequire('./tailwind.config.cjs').theme.extend.colors
const excluded = new Set(['slate', 'gray', 'zinc', 'neutral', 'stone', 'lightBlue', 'warmGray', 'trueGray', 'coolGray', 'blueGray'])
const palette = Object.keys(colors).filter(name => !excluded.has(name)).map(name => [name, colors[name]])

/** Emit literal v3 colors and host-owned primary/gray channels for CSS-first v4. */
function theme(fallback) {
  const lines = ['/* Generated by scripts/generate-peer-theme.mjs; do not edit. */', '@theme inline {']
  for (const [name, shades] of palette) {
    if (typeof shades === 'string') {
      lines.push(`  --color-${name}: ${shades};`)
    }
    else {
      for (const [shade, value] of Object.entries(shades)) lines.push(`  --color-${name}-${shade}: ${value};`)
    }
  }
  for (const [name, shades] of Object.entries(inherited)) {
    for (const [shade, value] of Object.entries(shades)) {
      const parsed = getHistoireColorChannels(parseColor(value))
      const variable = `--_histoire-color-${name}-${shade}`
      lines.push(`  --color-${name}-${shade}: rgb(var(${variable}${fallback ? `, ${parsed.channels}` : ''}) / var(${variable}-alpha, ${fallback ? parsed.alpha : 1}));`)
    }
  }
  lines.push('}', '')
  return lines.join('\n')
}

await Promise.all([
  writeFile(new URL('../src/style/theme.css', import.meta.url), theme(false)),
  writeFile(new URL('../src/style/peer-theme.css', import.meta.url), theme(true)),
])
